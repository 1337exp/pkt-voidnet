    c.push((
        "accept-max-blob",
        hs(|b| wire::write_accept(b, 0x77, h.client_random, 0, &[0xEE; MAX_BLOB]).unwrap()),
    ));
    c.push((
        "reject",
        hs(|b| wire::write_reject(b, 3, h.client_random).unwrap()),
    ));

    // --- must be dropped
    c.push(("drop-empty", vec![]));
    c.push(("drop-kind-01-sealed-reserved", vec![0x01, 0, 0, 0]));
    c.push(("drop-kind-ff", vec![0xFF; 20]));
    c.push(("drop-data-no-frames", raw(&[])));
    c.push(("drop-data-header-truncated", vec![0x00, 1, 2, 3]));
    c.push(("drop-frame-tag-13-reserved", raw(&[0x13])));
    c.push(("drop-frame-tag-20", raw(&[0x20])));
    c.push(("drop-frame-tag-ff", raw(&[0xFF])));
